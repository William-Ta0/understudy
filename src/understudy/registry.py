_TEXT_KEYS = {"name", "label", "text", "column", "option", "message"}


def _apply_vocabulary(x: Any, vocab: dict[str, str], hits: set[str], key: str | None = None) -> Any:
    """Swap vendor-default display text for the tenant's, only where the whole string is display text."""
    if not vocab:
        return x
    if isinstance(x, str):
        if key in _TEXT_KEYS and x in vocab:
            hits.add(f"{x} -> {vocab[x]}")
            return vocab[x]
        return x
    if isinstance(x, list):
        if key == "headers":
            out = []
            for v in x:
                if isinstance(v, str) and v in vocab:
                    hits.add(f"{v} -> {vocab[v]}")
                    out.append(vocab[v])
                else:
                    out.append(v)
            return out
        return [_apply_vocabulary(v, vocab, hits, key) for v in x]
    if isinstance(x, dict):
        if "value" in x and "mode" in x and key in _TEXT_KEYS and isinstance(x["value"], str) and x["value"] in vocab:
            hits.add(f"{x['value']} -> {vocab[x['value']]}")
            return {**x, "value": vocab[x["value"]]}
        if key == "row":  # table_cell row keys: both the column header and the key value are display text
            out = {}
            for k, v in x.items():
                nk = vocab.get(k, k)
                if nk != k:
                    hits.add(f"{k} -> {nk}")
                nv = _apply_vocabulary(v, vocab, hits, "text")
                out[nk] = nv
            return out
        return {k: _apply_vocabulary(v, vocab, hits, k) for k, v in x.items()}
    return x


def effective_profile(profile: AppProfile, tenant: TenantBinding) -> AppProfile:
    body = profile.dump()
    by_id = {c["id"]: c for c in body["conditions"]}
    for c in tenant.conditions:
        by_id[c.id] = c.dump()
    body["conditions"] = sorted(by_id.values(), key=lambda c: c.get("priority", 50))
    screens = {s["id"]: s for s in body["screens"]}
    for s in tenant.screens:
        screens[s.id] = s.dump()
    body["screens"] = list(screens.values())
    hits: set[str] = set()
    body = _apply_vocabulary(body, tenant.vocabulary, hits)
    return AppProfile.model_validate(body)


def effective_capability(cap: Capability, tenant: TenantBinding) -> tuple[Capability, list[str]]:
    """The capability as it should run for this tenant, plus a list of what was changed."""
    body = cap.dump()
    applied: list[str] = []
    hits: set[str] = set()
    for field in ("steps", "outputs", "success"):
        body[field] = _apply_vocabulary(body[field], tenant.vocabulary, hits, field)
    applied += [f"vocabulary: {h}" for h in sorted(hits)]
    ov = tenant.capability_overrides.get(cap.id)
    if ov:
        for key, target in ov.targets.items():
            if key.startswith("output:"):
                name = key.split(":", 1)[1]
                body["outputs"][name]["source"] = target.dump()
            else:
                step = next((s for s in body["steps"] if s["id"] == key), None)
                if step is None:
                    raise KeyError(f"tenant {tenant.id} overrides unknown step {key!r} of {cap.id}")
                step["target"] = target.dump()
            applied.append(f"override: {key} ({ov.reason})")
    return Capability.model_validate(body), applied
